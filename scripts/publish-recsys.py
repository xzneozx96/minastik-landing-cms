#!/usr/bin/env python3
"""
Publish the "Recommender Systems from Zero" book into public/recsys/.

The book is a static Quarto site. Its rendered output lives in public/recsys/
and is served by Next.js (see the /recsys rewrite in next.config.js).

A raw `quarto render` output is NOT publishable as-is, because two patches are
applied on top of the Quarto output and are not generated by Quarto:

  1. <base href="/recsys/"> in index.html
     Quarto emits index.html's asset paths as root-relative ("site_libs/...").
     At the URL /recsys (no trailing slash) the browser would resolve them
     against the domain root and every stylesheet/script would 404. The base
     tag pins them to /recsys/. Chapter pages use "../site_libs/..." and are
     already correct, so the base tag goes in index.html only.

  2. The Minastik brand layer (site_libs/minastik-brand.css + .js)
     Injected into <head> and before </body> of every Quarto page. The two
     brand files themselves are stored in git and restored from HEAD, because
     the Quarto build never produces them.

Usage:
    python3 scripts/publish-recsys.py <path-to-quarto-output> [options]

Options:
    --check          Validate the source folder only; do not touch public/recsys
    --commit <msg>   Commit public/recsys after publishing
    --push           Push to origin main after committing
    --no-verify      Skip the post-publish verification pass

Example:
    python3 scripts/publish-recsys.py ~/Documents/.../recsys-site-v2.0 --commit "feat(recsys): publish v2.0" --push
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parent.parent
TARGET = REPO / "public" / "recsys"
BRAND_CSS_PATH = "public/recsys/site_libs/minastik-brand.css"
BRAND_JS_PATH = "public/recsys/site_libs/minastik-brand.js"

BASE_TAG = '<base href="/recsys/">'

BRAND_CSS_BLOCK = """  <!-- minastik-brand -->
  <script>document.documentElement.setAttribute('data-bs-theme',localStorage.getItem('mnk-theme')||'light');</script>
  <link rel="stylesheet" href="/recsys/site_libs/minastik-brand.css">
  <!-- /minastik-brand -->
"""

BRAND_JS_BLOCK = """  <!-- minastik-brand-js -->
  <script src="/recsys/site_libs/minastik-brand.js"></script>
  <!-- /minastik-brand-js -->
"""

# Standalone widgets keep their own styling: the brand layer's dark-mode body
# rules would give them a dark background under hardcoded dark text.
STANDALONE_GLOBS = ("demos/*.html",)


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO, check=True, **kw)


def info(msg: str) -> None:
    print(f"  {msg}")


def fail(msg: str) -> "NoReturn":  # type: ignore[valid-type]
    sys.stdout.flush()
    print(f"\nERROR: {msg}", file=sys.stderr)
    sys.exit(1)


# --------------------------------------------------------------------------
# 1. validate the source build
# --------------------------------------------------------------------------
def validate_source(src: pathlib.Path) -> list[pathlib.Path]:
    if not src.is_dir():
        fail(f"source folder does not exist: {src}")

    index = src / "index.html"
    if not index.is_file():
        fail(f"missing index.html in {src}")

    chapters_dir = src / "chapters"
    if not chapters_dir.is_dir():
        fail(f"missing chapters/ in {src}")

    chapters = sorted(chapters_dir.glob("*.html"))
    if not chapters:
        fail(f"no chapter pages found in {chapters_dir}")

    if not (src / "site_libs").is_dir():
        fail(f"missing site_libs/ in {src} — is this a rendered Quarto output?")

    # A rendered build always carries the Quarto generator meta tag.
    head = index.read_text(encoding="utf-8", errors="ignore")[:2000]
    if "quarto" not in head.lower():
        fail("index.html has no Quarto generator meta tag — this does not look like a Quarto render")

    search_json = src / "search.json"
    if search_json.is_file():
        try:
            json.loads(search_json.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            fail(f"search.json is not valid JSON: {exc}")

    info(f"source OK: {len(chapters)} chapters, site_libs present")
    return chapters


# --------------------------------------------------------------------------
# 2. install the build
# --------------------------------------------------------------------------
def install_source(src: pathlib.Path) -> None:
    if TARGET.exists():
        shutil.rmtree(TARGET)
    shutil.copytree(src, TARGET, ignore=shutil.ignore_patterns(".DS_Store"))
    info(f"copied build into {TARGET.relative_to(REPO)}")


# --------------------------------------------------------------------------
# 3. restore the brand layer from git
# --------------------------------------------------------------------------
def restore_brand_layer() -> None:
    for rel in (BRAND_CSS_PATH, BRAND_JS_PATH):
        dest = REPO / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        try:
            content = subprocess.run(
                ["git", "show", f"HEAD:{rel}"],
                cwd=REPO, capture_output=True, check=True,
            ).stdout
        except subprocess.CalledProcessError:
            fail(f"could not restore {rel} from git — it must be committed before publishing")
        dest.write_bytes(content)
        info(f"restored {rel} from git")


# --------------------------------------------------------------------------
# 4. apply the patches
# --------------------------------------------------------------------------
def is_standalone(rel: pathlib.Path) -> bool:
    return any(rel.match(g) for g in STANDALONE_GLOBS)


def patch_page(path: pathlib.Path, with_base: bool) -> bool:
    html = path.read_text(encoding="utf-8")
    changed = False

    if with_base and BASE_TAG not in html:
        anchor = '<meta charset="utf-8">'
        if anchor not in html:
            fail(f"{path}: expected a <meta charset> anchor to place the base tag")
        html = html.replace(anchor, f"{anchor}\n{BASE_TAG}", 1)
        changed = True

    if "<!-- minastik-brand -->" not in html:
        if "</head>" not in html:
            fail(f"{path}: no </head> to inject the brand stylesheet")
        if "</body>" not in html:
            fail(f"{path}: no </body> to inject the brand script")
        html = html.replace("</head>", f"{BRAND_CSS_BLOCK}</head>", 1)
        html = html.replace("</body>", f"{BRAND_JS_BLOCK}</body>", 1)
        changed = True

    if changed:
        path.write_text(html, encoding="utf-8")
    return changed


def apply_patches() -> None:
    index = TARGET / "index.html"
    patch_page(index, with_base=True)
    info("patched index.html (base tag + brand layer)")

    chapters = sorted((TARGET / "chapters").glob("*.html"))
    for chap in chapters:
        patch_page(chap, with_base=False)
    info(f"patched {len(chapters)} chapter pages (brand layer)")

    standalone = [p for p in TARGET.rglob("*.html") if is_standalone(p.relative_to(TARGET))]
    for page in standalone:
        info(f"skipped {page.relative_to(TARGET)} (standalone, self-styled)")


# --------------------------------------------------------------------------
# 5. verify
# --------------------------------------------------------------------------
def verify() -> bool:
    print("\nVerifying published site...")
    ok = True

    index = (TARGET / "index.html").read_text(encoding="utf-8", errors="ignore")
    if BASE_TAG not in index:
        fail("index.html is missing the <base href=\"/recsys/\"> tag")
    info("base tag present in index.html")

    quarto_pages = [TARGET / "index.html"] + sorted((TARGET / "chapters").glob("*.html"))
    for page in quarto_pages:
        txt = page.read_text(encoding="utf-8", errors="ignore")
        if "minastik-brand.css" not in txt or "minastik-brand.js" not in txt:
            fail(f"{page.relative_to(TARGET)} is missing the brand layer")
    info(f"brand layer present in all {len(quarto_pages)} Quarto pages")

    for rel in (BRAND_CSS_PATH, BRAND_JS_PATH):
        if not (REPO / rel).is_file():
            fail(f"{rel} is missing from site_libs/")
    info("brand files present in site_libs/")

    # every local asset reference must resolve on disk
    pub = (REPO / "public").resolve()
    broken: list[tuple[str, str]] = []
    checked = 0
    for html in sorted((pub / "recsys").rglob("*.html")):
        url_path = "/" + str(html.relative_to(pub))
        base_dir = os.path.dirname(url_path)
        txt = html.read_text(encoding="utf-8", errors="ignore")
        for ref in re.findall(r'(?:src|href)="([^"]+)"', txt):
            if ref.startswith(("http://", "https://", "#", "mailto:", "data:")):
                continue
            target = ref if ref.startswith("/") else os.path.normpath(os.path.join(base_dir, ref))
            if not target.startswith("/recsys/"):
                continue
            # "/recsys/" is the site root; Next.js rewrites it to index.html.
            if target == "/recsys/":
                continue
            checked += 1
            if not (pub / target.lstrip("/")).is_file():
                broken.append((url_path, ref))
    if broken:
        ok = False
        sys.stdout.flush()
        print(f"  FAIL {len(broken)} broken asset reference(s):", file=sys.stderr)
        for page, ref in broken[:15]:
            print(f"    {page} -> {ref}", file=sys.stderr)
    else:
        info(f"{checked} local asset references all resolve")

    search_json = TARGET / "search.json"
    if search_json.is_file():
        try:
            entries = len(json.loads(search_json.read_text(encoding="utf-8")))
            info(f"search.json valid ({entries} entries)")
        except json.JSONDecodeError as exc:
            ok = False
            print(f"  FAIL search.json invalid: {exc}", file=sys.stderr)

    if not ok:
        print("\nVERIFICATION FAILED", file=sys.stderr)
        return False
    print("\nVerification passed.")
    return True


# --------------------------------------------------------------------------
# 6. commit / push
# --------------------------------------------------------------------------
def commit_and_push(message: str, push: bool) -> None:
    run(["git", "add", "-A", "public/recsys", "public/llms.txt"])
    status = run(["git", "status", "--short"], capture_output=True, text=True).stdout.strip()
    if not status:
        info("no changes to commit")
        return
    run(["git", "commit", "-m", message])
    info(f"committed: {message.splitlines()[0]}")
    if push:
        run(["git", "push", "origin", "main"])
        info("pushed to origin main")


# --------------------------------------------------------------------------
def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", help="path to the rendered Quarto output")
    parser.add_argument("--check", action="store_true", help="validate the source only")
    parser.add_argument("--commit", metavar="MSG", help="commit after publishing")
    parser.add_argument("--push", action="store_true", help="push to origin main after committing")
    parser.add_argument("--no-verify", action="store_true", help="skip verification")
    args = parser.parse_args()

    src = pathlib.Path(args.source).expanduser().resolve()

    print(f"Publishing RecSys book from:\n  {src}\n")
    validate_source(src)

    if args.check:
        print("\n--check only: source is valid, nothing was written.")
        return 0

    install_source(src)
    restore_brand_layer()
    apply_patches()

    if not args.no_verify and not verify():
        return 1

    if args.commit:
        commit_and_push(args.commit, args.push)
    else:
        print("\nNot committed. Re-run with --commit \"<message>\" to commit, add --push to deploy.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
